"""Deterministic census table (UPB-det, forward) on the 10,500 benchmark instances.
Reads data/census_upb_det_10500.csv (UPB-det value, walk status and CPU from bound_analyses/det/run_det_all.py;
Chen-Song bound as reported with HgR, PCH bound and published HgR UB). Baseline B = ceil(max(L_CS, LB_PCH)).
Usage: python3 -I make_tab_lb_census_det.py [OUTDIR]  (default ./tables_out)"""
import csv, os, sys
import math, statistics
HERE = os.path.dirname(os.path.abspath(__file__))
CSV = os.path.join(HERE, "..", "..", "data", "census_upb_det_10500.csv")
OUT = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else "tables_out"); os.makedirs(OUT, exist_ok=True)
R, G = {}, {}
for x in csv.DictReader(open(CSV)):
    k = x["instance"]; R[k] = dict(lb_det=float(x["upb_det"]), exact_det=int(x["upb_det_walk_exact"]), cpu=float(x["upb_det_cpu_s"]))
    G[k] = dict(g=x["dock_group"], n1=int(x["n1"]), lb_hgr=float(x["lb_chen_song_hgr"]), lb_pch=float(x["lb_pch"]), ub_hgr=float(x["ub_hgr_published"]))
ks = sorted(R); assert len(ks) == 10500 and all(k in G for k in ks), (len(ks),)
B = [math.ceil(max(G[k]['lb_hgr'], G[k]['lb_pch']) - 1e-9) for k in ks]
U = [R[k]['lb_det'] for k in ks]; UB = [G[k]['ub_hgr'] for k in ks]
fin = [bool(R[k]['exact_det']) for k in ks]; cpu = [R[k]['cpu'] for k in ks]
n1 = [G[k]['n1'] for k in ks]; grp = [G[k]['g'] for k in ks]
assert all(u <= ub + 1e-9 for u, ub in zip(U, UB))
gain = [(u - b) / b * 100 for u, b in zip(U, B)]
mean = statistics.fmean
def row(lab, m):
    I = [i for i in range(len(ks)) if m(i)]
    g = [gain[i] for i in I]
    return (f"{lab} & {len(I):,} & {mean(g):.2f} & {statistics.median(g):.2f} & {max(g):.2f} & {sum(U[i] < B[i] - 1e-9 for i in I)} & "
            f"{mean([(UB[i]-B[i])/B[i] for i in I])*100:.1f} & {mean([(UB[i]-U[i])/U[i] for i in I])*100:.1f} & "
            f"{mean([fin[i] for i in I])*100:.0f} & {mean([cpu[i] for i in I]):.1f} / {max(cpu[i] for i in I):.0f} \\\\")
names = {'m2': '$m=2$', 'm4': '$m=4$', 'm10': '$m=10$', 'u24': 'U(2,4)', 'u210': 'U(2,10)'}
rows = [row('All', lambda i: True), '\\midrule']
rows += [row(f'$n_1={k}$', lambda i, k=k: n1[i] == k) for k in range(20, 81, 10)] + ['\\midrule']
rows += [row(names[g], lambda i, g=g: grp[i] == g) for g in ('m2', 'm4', 'm10', 'u24', 'u210')]
out = r"""%% Generated by make_tab_lb_census_det.py. Do not edit by hand.
%% Source: data/census_upb_det_10500.csv.
\begin{table}[htbp]
\centering
\caption{Census of the deterministic bound \UPB-det (forward instance) on all 10,500 benchmark instances. $B$ is the
best earlier bound, $\lceil\max(L_{\mathrm{CS}},\LBPCH)\rceil$, with $L_{\mathrm{CS}}$ as reported with the published
HgR results. ``Gain'' is $(\UPB-B)/B$ in \%. The HgR gaps use the published HgR upper bound and
$(\mathrm{UB}-\mathrm{LB})/\mathrm{LB}$. ``Fin.'' is the share of instances on which the walk finished within its
step cap. The census covers every instance, so the values are population means, not estimates.}
\label{tab:lbcensus}
\small
\begin{adjustbox}{max width=\textwidth}
\begin{tabular}{lrrrrrrrrr}
\toprule
 & & \multicolumn{4}{c}{Gain of \UPB{} over $B$ (\%)} & \multicolumn{2}{c}{HgR gap (\%)} & & \\
\cmidrule(lr){3-6}\cmidrule(lr){7-8}
Slice & $n$ & mean & median & max & \# lower & vs $B$ & vs \UPB & Fin.\ (\%) & CPU s (mean / max) \\
\midrule
""" + "\n".join(rows) + r"""
\bottomrule
\end{tabular}
\end{adjustbox}
\end{table}
"""
open(os.path.join(OUT, 'tab_lb_census_det.tex'), 'w').write(out)
print("\n".join(rows))
