"""Generate the LaTeX tables of the cross-dock EJOR draft from the result files.

Reads only the analysis outputs under code/ (as shipped, or regenerated by the run scripts) and writes *.tex into OUTDIR.
Every table carries a comment with its source file. Numbers are copied as printed in the source files;
nothing is recomputed here. Usage: python3 -I make_tables.py [OUTDIR]  (default ./tables_out)
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
import sys
FD = os.path.abspath(os.path.join(HERE, ".."))
OUT = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else "tables_out"); os.makedirs(OUT, exist_ok=True)


def src(rel):
    return os.path.join(FD, rel)


def read(rel):
    with open(src(rel), encoding="utf-8") as f:
        return f.read()


def write(name, rel_sources, body):
    head = "% Generated by make_tables.py. Do not edit by hand.\n"
    for r in rel_sources:
        head += f"% Source: code/{r}\n"
    with open(os.path.join(OUT, name), "w", encoding="utf-8") as f:
        f.write(head + body)


def num(x):
    """Typeset a number string with a proper minus sign."""
    x = str(x)
    return "$-$" + x[1:] if x.startswith("-") else x


GROUP = {"m2": "$m=2$", "m4": "$m=4$", "m10": "$m=10$", "u24": "U(2,4)", "u210": "U(2,10)"}


# ---------------------------------------------------------------- LB census, by n1 and dock group
def tab_lb_census():
    rel = "lower_bounds/analysis_full_10500.txt"
    t = read(rel)
    pat = re.compile(r"^(\S+)\s+n=\s*(\d+) gain%=\s*([\d.]+) \(max\s*([\d.]+), worse (\d+)\) gapHgR_vsG0=\s*([\d.]+) "
                     r"vsNew=\s*([\d.]+) pub=\s*([\d.]+) exact=([\d.]+) cpu=([\d.]+)/(\d+)", re.M)
    rows = []
    for m in pat.finditer(t):
        tag, n, gain, mx, worse, g0, gnew, pub, ex, cpu, cpumax = m.groups()
        if tag == "all":
            lab = "All"
        elif tag.startswith("n1="):
            lab = f"$n_1={tag[3:]}$"
        else:
            lab = GROUP[tag[2:]]
        rows.append((tag, f"{lab} & {int(n):,} & {gain} & {mx} & {worse} & {g0} & {gnew} & {float(ex)*100:.0f} & {cpu} / {cpumax} \\\\"))
    body = r"""\begin{table}[t]
\centering
\caption{Lower-bound census on the 10,500 benchmark instances. ``Gain'' is $(\LBUs-L_0)/L_0$, where $L_0$ is the
largest earlier bound available for the instance (the Chen--Song-type bound reported with the HgR results, \LBPCH,
and the cheap bounds \LBetwo{} and \LBload). The last three gap columns use the published HgR upper bound and the gap
$(\mathrm{UB}-\mathrm{LB})/\mathrm{LB}$. ``Exact'' is the share of instances on which the knapsack walk finished within
the 4\,s CPU cap. The census covers every instance, so the values are population means, not estimates.}
\label{tab:lbcensus}
\small
\begin{adjustbox}{max width=\textwidth}
\begin{tabular}{lrrrrrrrr}
\toprule
 & & \multicolumn{3}{c}{Gain of \LBUs{} over $L_0$ (\%)} & \multicolumn{2}{c}{HgR gap (\%)} & & \\
\cmidrule(lr){3-5}\cmidrule(lr){6-7}
Slice & $n$ & mean & max & \# lower & vs $L_0$ & vs \LBUs & Exact (\%) & CPU s (mean / max) \\
\midrule
"""
    order = [r for r in rows if r[0] == "all"] + [r for r in rows if r[0].startswith("n1=")] + \
            sorted([r for r in rows if r[0].startswith("g=")], key=lambda r: ["g=m2", "g=m4", "g=m10", "g=u24", "g=u210"].index(r[0]))
    for i, (tag, line) in enumerate(order):
        body += line + "\n"
        if i == 0 or (tag.startswith("n1=") and tag == "n1=80"):
            body += "\\midrule\n"
    body += r"""\bottomrule
\end{tabular}
\end{adjustbox}
\end{table}
"""
    write("tab_lb_census.tex", [rel], body)


# ---------------------------------------------------------------- LB census, alternative baselines
def tab_lb_baselines():
    rel = "confirmation_eacdc/g1_nonown.txt"
    t = read(rel)
    blocks = re.split(r"^== ", t, flags=re.M)
    lab = {"vs best non-own max(lb_hgr, lb_pch) raw": r"$\max(L_{\mathrm{CS}},\LBPCH)$",
           "vs ceil(best non-own)": r"$\lceil\max(L_{\mathrm{CS}},\LBPCH)\rceil$",
           "vs lb_hgr only raw": r"$L_{\mathrm{CS}}$ (as reported)",
           "vs ceil(lb_hgr)": r"$\lceil L_{\mathrm{CS}}\rceil$",
           "vs old baseline lo_cheap (incl. own e2/load)": r"$L_0$ (adds \LBetwo, \LBload)"}
    pat = re.compile(r"^(vs .*?)\s+n=(\d+) mean ([\d.]+)%\s+q0/10/50/90/100 ([\d.]+) / ([\d.]+) / ([\d.]+) / ([\d.]+) / ([\d.]+)\s+frac<0 ([\d.]+)", re.M)
    body = r"""\begin{table}[t]
\centering
\caption{Gain (\%) of the new bound over several earlier baselines, on all 10,500 instances. $L_{\mathrm{CS}}$ is the
Chen--Song-type bound as reported with the public HgR results. Quantiles are over instances. No instance has a
negative gain under any baseline.}
\label{tab:lbbaselines}
\small
\begin{adjustbox}{max width=\textwidth}
\begin{tabular}{llrrrrrr}
\toprule
New bound & Baseline & mean & $q_{0}$ & $q_{10}$ & $q_{50}$ & $q_{90}$ & $q_{100}$ \\
\midrule
"""
    parts = []
    for b in blocks[1:]:
        name = b.splitlines()[0].strip()
        nb = r"\LBUs" if name == "LB_U*" else r"\LBstar"
        lines = []
        for m in pat.finditer(b):
            k, n, mean, q0, q1, q5, q9, qx, neg = m.groups()
            lines.append(f"{nb} & {lab[k.strip()]} & {mean} & {q0} & {q1} & {q5} & {q9} & {qx} \\\\")
        parts.append("\n".join(lines))
    body += "\n\\midrule\n".join(parts) + "\n"
    body += r"""\bottomrule
\end{tabular}
\end{adjustbox}
\end{table}
"""
    write("tab_lb_baselines.tex", [rel], body)


# ---------------------------------------------------------------- matched UB comparison
def parse_match(t):
    out = {}
    m = re.search(r"CPU-matched \(ILS at the run's own EACDC CPU\)\s+n=(\d+) ([-\d.]+)% \[([-\d.]+), ([-\d.]+)\]\s+W/T/L (\S+)", t)
    out["cpu"] = m.groups()
    m = re.search(r"eval-matched: EACDC evalPop calls \(conservative\)\s+n=(\d+) ([-\d.]+)% \[([-\d.]+), ([-\d.]+)\]\s+W/T/L (\S+)", t)
    out["ev"] = m.groups()
    m = re.search(r"eval-matched: evalPop \+ init schedules\s+n=(\d+) ([-\d.]+)% \[([-\d.]+), ([-\d.]+)\]\s+W/T/L (\S+)", t)
    out["evi"] = m.groups()
    out["byn"] = re.findall(r"n1=(\d+): ([-\d.]+) / ([-\d.]+) \(n=(\d+)\)", t)
    m = re.search(r"EACDC CPU per run: mean ([\d.]+) s \(median ([\d.]+), max ([\d.]+)\); evals EACDC mean (\d+); ILS evals within the same CPU mean (\d+) \(ratio ([\d.]+)\)", t)
    out["cost"] = m.groups()
    return out


def tab_ub_matched():
    rc, rd = "confirmation_eacdc/ana_confirm.txt", "confirmation_eacdc/ana_m105.txt"
    C, D = parse_match(read(rc)), parse_match(read(rd))

    def ci(x):
        return f"{num(x[1])} [{num(x[2])}, {num(x[3])}]"
    body = r"""\begin{table}[t]
\centering
\caption{ILS against the static-configuration EACDC, matched run by run. Values are the mean paired difference
$(\mathrm{UB}_{\mathrm{ILS}}-\mathrm{UB}_{\mathrm{EACDC}})/\mathrm{UB}_{\mathrm{EACDC}}$ in \%, with 95\% bootstrap
intervals over instances. Negative values favour ILS. W/T/L counts the instances (seed means) on which ILS is
better, equal (relative tolerance $10^{-9}$) or worse. The confirmation instances were generated after the protocol
was registered. The development instances were used to design ILS.}
\label{tab:ubmatched}
\footnotesize
\begin{adjustbox}{max width=\textwidth}
\begin{tabular}{lllll}
\toprule
 & \multicolumn{2}{c}{Confirmation: 210 fresh instances, seeds 11--13} & \multicolumn{2}{c}{Development: 105 instances, seeds 1--5} \\
\cmidrule(lr){2-3}\cmidrule(lr){4-5}
Budget matched on & Mean [95\% CI] & W/T/L & Mean [95\% CI] & W/T/L \\
\midrule
"""
    for key, lab in (("ev", "Evaluations (generations)"), ("evi", "Evaluations (with initial pop.)"),
                     ("cpu", "CPU time")):
        body += f"{lab} & {ci(C[key])} & {C[key][4]} & {ci(D[key])} & {D[key][4]} \\\\\n"
    body += "\\midrule\n\\multicolumn{5}{l}{By $n_1$, mean only, \\%: CPU-matched / evaluation-matched (generations)} \\\\\n"
    dd = {n: (a, b) for n, a, b, _ in D["byn"]}
    for n, a, b, k in C["byn"]:
        body += f"\\quad $n_1={n}$ & {num(a)} / {num(b)} & & {num(dd[n][0])} / {num(dd[n][1])} & \\\\\n"
    body += "\\midrule\n"
    body += (f"EACDC CPU per run, s: mean (median, max) & {C['cost'][0]} ({C['cost'][1]}, {C['cost'][2]}) & & "
             f"{D['cost'][0]} ({D['cost'][1]}, {D['cost'][2]}) & \\\\\n")
    body += (f"Evaluations per run: EACDC / ILS & {int(C['cost'][3]):,} / {int(C['cost'][4]):,} & & "
             f"{int(D['cost'][3]):,} / {int(D['cost'][4]):,} & \\\\\n")
    body += r"""\bottomrule
\end{tabular}
\end{adjustbox}
\end{table}
"""
    write("tab_ub_matched.tex", [rc, rd], body)


# ---------------------------------------------------------------- exact optima, true gaps
def tab_exact_gaps():
    rel = "exact_cpsat/ana_exact_all.txt"
    t = read(rel)
    pat = re.compile(r"true gap (.+?)\s+mean ([\d.]+)% \[([\d.]+)%, ([\d.]+)%\], median ([\d.]+)%, max ([\d.]+)%, at OPT ([\d.]+)")
    name = {"HgR": "HgR (published; unmatched reference)", "EACDC (1 default run)": "EACDC (one default run)",
            "ILS 4 s": "ILS, 4\\,s", "ILS 10 s": "ILS, 10\\,s"}
    body = r"""\begin{table}[t]
\centering
\caption{Distance to proven optima on the 62 instances ($n_1=20$) that CP-SAT solved within 300\,s, in \%,
$(\mathrm{UB}-\mathrm{OPT})/\mathrm{OPT}$. Intervals are 95\% bootstrap intervals over instances. The solved
instances are the easier part of $n_1=20$, so the values describe that subset only.}
\label{tab:exactgaps}
\small
\begin{adjustbox}{max width=\textwidth}
\begin{tabular}{lrrrr}
\toprule
Method & Mean [95\% CI] & Median & Max & At optimum (\%) \\
\midrule
"""
    for m in pat.finditer(t):
        k, mean, lo, hi, med, mx, at = m.groups()
        body += f"{name[k.strip()]} & {mean} [{lo}, {hi}] & {med} & {mx} & {float(at)*100:.1f} \\\\\n"
    m = re.search(r"LB\* gap to OPT \(OPT-LB\)/OPT on solved: mean ([\d.]+)%, median ([\d.]+)%, max ([\d.]+)%", t)
    m2 = re.search(r"Chen-Song LB gap to OPT on solved: mean ([\d.]+)%", t)
    m3 = re.search(r"LB\* \(max fwd, rev\) = OPT on (\d+)/(\d+)", t)
    body += "\\midrule\n"
    body += f"\\LBstar{{}} (lower bound; $(\\mathrm{{OPT}}-\\mathrm{{LB}})/\\mathrm{{OPT}}$) & {m.group(1)} & {m.group(2)} & {m.group(3)} & {float(m3.group(1))/float(m3.group(2))*100:.1f} \\\\\n"
    body += f"Chen--Song bound (same measure) & {m2.group(1)} & & & \\\\\n"
    body += r"""\bottomrule
\end{tabular}
\end{adjustbox}
\end{table}
"""
    write("tab_exact_gaps.tex", [rel], body)


